import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const vendorDirectory = path.join(repositoryRoot, 'scripts', 'vendor');
const posthogSource = path.join(
  repositoryRoot,
  'node_modules',
  'posthog-js',
  'dist',
  'module.slim.no-external.js'
);
const posthogTarget = path.join(vendorDirectory, 'posthog.js');
const posthogLicenseSource = path.join(repositoryRoot, 'node_modules', 'posthog-js', 'LICENSE');
const posthogLicenseTarget = path.join(vendorDirectory, 'posthog.LICENSE.txt');
const configTarget = path.join(repositoryRoot, 'scripts', 'analytics-config.js');

const publicToken = process.env.POSTHOG_PUBLIC_TOKEN?.trim() || '';
const apiHost = process.env.POSTHOG_HOST?.trim() || 'https://eu.i.posthog.com';
const configSource = `// Generated by npm run analytics:build. Do not commit this file.\n` +
  `export const POSTHOG_CONFIG = Object.freeze(${JSON.stringify({ publicToken, apiHost })});\n`;

await mkdir(vendorDirectory, { recursive: true });
await copyFile(posthogSource, posthogTarget);
const posthogLicense = await readFile(posthogLicenseSource, 'utf8');
await writeFile(posthogLicenseTarget, posthogLicense.replace(/[ \t]+$/gm, ''), 'utf8');
await writeFile(configTarget, configSource, 'utf8');

console.log(`Built privacy-conscious analytics assets (${publicToken ? 'configured' : 'disabled'}).`);
